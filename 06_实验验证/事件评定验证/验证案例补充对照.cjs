'use strict';
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm'), assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../..');
const old = fs.readFileSync(path.join(root, '07_成果输出/情景库思路演示.html'), 'utf8');
const page = fs.readFileSync(path.join(root, '07_成果输出/演示版本/2026-10-28-自适应指标补全与协同决策/index.html'), 'utf8');
const script = h => h.match(/<script id="assessment-model">([\s\S]*?)<\/script>/)[1];
assert.equal(script(page), script(old), '演示内嵌的评定模型必须与原模型一致');
const context = {module:{exports:{}}}; vm.createContext(context); vm.runInContext(script(page), context);
context.AssessmentV2 = context.module.exports;
const fn = page.match(/    function compareArrivalWave\(selected\)\{[\s\S]*?\r?\n    \}\r?\n    function renderComparison/);
assert.ok(fn); vm.runInContext(fn[0].replace(/\r?\n    function renderComparison$/, ''), context);
const test = s => JSON.parse(JSON.stringify(context.compareArrivalWave(s)));
const front = test('front'), even = test('even');
assert.deepEqual(front.before.levels, [3,4]);
assert.equal(front.before.level, 3);
assert.equal(front.after.level, 3);
assert.equal(even.after.level, 4);
assert.ok(Math.abs(front.before.peak[0]-50)<1e-7 && Math.abs(front.before.peak[1]-110)<1e-7);
assert.ok(Math.abs(front.after.peak[0]-110)<1e-7);
assert.ok(Math.abs(even.after.peak[0]-50)<1e-7);
assert.equal(test('unknown'), null);
assert.equal(test('multi'), null);
for (const match of page.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)) new vm.Script(match[1]);
console.log('通过：原模型一致、未知范围、两种节奏的等级与峰值、未知和多波次阻止映射、脚本语法');
